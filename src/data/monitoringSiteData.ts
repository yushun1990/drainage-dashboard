function parseCoordinate(value: string): number {
  const parsed = Number(value.trim())

  return Number.isFinite(parsed) ? parsed : 0
}

function isInDemoBounds(coordinate: DrainageMapPoint['coordinate']): boolean {
  const [longitude, latitude] = coordinate

  return (
    longitude >= demoBounds.minLongitude &&
    longitude <= demoBounds.maxLongitude &&
    latitude >= demoBounds.minLatitude &&
    latitude <= demoBounds.maxLatitude
  )
}

